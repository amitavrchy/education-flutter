import 'package:material_ui/material_ui.dart';

import '../../../core/l10n/tr.dart';

enum NoteType {
  freeform(Tr('মুক্ত নোট', 'Free note'), Icons.edit_note),
  short(Tr('সংক্ষিপ্ত নোট', 'Short notes'), Icons.short_text),
  detailed(Tr('বিস্তারিত নোট', 'Detailed notes'), Icons.article_outlined),
  revision(Tr('রিভিশন নোট', 'Revision notes'), Icons.flash_on_outlined),
  formulaSheet(Tr('সূত্র তালিকা', 'Formula sheet'), Icons.functions),
  definitionSheet(Tr('সংজ্ঞা তালিকা', 'Definition sheet'), Icons.menu_book_outlined),
  keyTakeaways(Tr('মূল শিক্ষা', 'Key takeaways'), Icons.checklist),
  importantQuestions(Tr('গুরুত্বপূর্ণ প্রশ্ন', 'Important questions'), Icons.help_outline);

  const NoteType(this.label, this.icon);

  final Tr label;
  final IconData icon;
}

enum NoteSource {
  manual(Tr('নিজে লেখা', 'Written by you')),
  chapter(Tr('অধ্যায় থেকে', 'From a chapter')),
  topic(Tr('টপিক থেকে', 'From a topic')),
  question(Tr('প্রশ্ন থেকে', 'From a question')),
  conversation(Tr('AI কথোপকথন থেকে', 'From an AI chat')),
  upload(Tr('আপলোড থেকে (সিমুলেটেড)', 'From an upload (simulated)'));

  const NoteSource(this.label);

  final Tr label;
}

@immutable
class NoteVersion {
  const NoteVersion({required this.at, required this.title, required this.body});

  factory NoteVersion.fromJson(Map<String, dynamic> j) =>
      NoteVersion(at: DateTime.parse(j['at'] as String), title: j['title'] as String, body: j['body'] as String);

  final DateTime at;
  final String title;
  final String body;

  Map<String, dynamic> toJson() => {'at': at.toIso8601String(), 'title': title, 'body': body};
}

@immutable
class Note {
  const Note({
    required this.id,
    required this.title,
    required this.body,
    required this.createdAt,
    required this.updatedAt,
    this.type = NoteType.freeform,
    this.source = NoteSource.manual,
    this.folder,
    this.tags = const [],
    this.favorite = false,
    this.subjectId,
    this.chapterId,
    this.topicId,
    this.linkedIds = const [],
    this.history = const [],
    this.aiGenerated = false,
  });

  factory Note.fromJson(Map<String, dynamic> j) => Note(
    id: j['id'] as String,
    title: j['title'] as String,
    body: j['body'] as String,
    createdAt: DateTime.parse(j['createdAt'] as String),
    updatedAt: DateTime.parse(j['updatedAt'] as String),
    type: NoteType.values.byName(j['type'] as String? ?? 'freeform'),
    source: NoteSource.values.byName(j['source'] as String? ?? 'manual'),
    folder: j['folder'] as String?,
    tags: List<String>.from(j['tags'] as List? ?? const []),
    favorite: j['favorite'] as bool? ?? false,
    subjectId: j['subjectId'] as String?,
    chapterId: j['chapterId'] as String?,
    topicId: j['topicId'] as String?,
    linkedIds: List<String>.from(j['linkedIds'] as List? ?? const []),
    history: [for (final h in j['history'] as List? ?? const []) NoteVersion.fromJson(h as Map<String, dynamic>)],
    aiGenerated: j['aiGenerated'] as bool? ?? false,
  );

  final String id;
  final String title;

  /// Markdown + math, rendered with RichContent.
  final String body;
  final DateTime createdAt;
  final DateTime updatedAt;
  final NoteType type;
  final NoteSource source;
  final String? folder;
  final List<String> tags;
  final bool favorite;
  final String? subjectId;
  final String? chapterId;
  final String? topicId;

  /// Linked notes (note linking).
  final List<String> linkedIds;

  /// Earlier versions, newest first (max 10).
  final List<NoteVersion> history;

  /// Generated by the simulated AI (labelled in the UI).
  final bool aiGenerated;

  Note copyWith({
    String? title,
    String? body,
    DateTime? updatedAt,
    NoteType? type,
    String? Function()? folder,
    List<String>? tags,
    bool? favorite,
    List<String>? linkedIds,
    List<NoteVersion>? history,
  }) => Note(
    id: id,
    title: title ?? this.title,
    body: body ?? this.body,
    createdAt: createdAt,
    updatedAt: updatedAt ?? this.updatedAt,
    type: type ?? this.type,
    source: source,
    folder: folder == null ? this.folder : folder(),
    tags: tags ?? this.tags,
    favorite: favorite ?? this.favorite,
    subjectId: subjectId,
    chapterId: chapterId,
    topicId: topicId,
    linkedIds: linkedIds ?? this.linkedIds,
    history: history ?? this.history,
    aiGenerated: aiGenerated,
  );

  Map<String, dynamic> toJson() => {
    'id': id,
    'title': title,
    'body': body,
    'createdAt': createdAt.toIso8601String(),
    'updatedAt': updatedAt.toIso8601String(),
    'type': type.name,
    'source': source.name,
    'folder': folder,
    'tags': tags,
    'favorite': favorite,
    'subjectId': subjectId,
    'chapterId': chapterId,
    'topicId': topicId,
    'linkedIds': linkedIds,
    'history': [for (final h in history) h.toJson()],
    'aiGenerated': aiGenerated,
  };
}
